export function getFlow(slug: string): AgentFlow | undefined {
  return flows.find((flow) => flow.slug === slug);
}

export function searchFlows(query: string): AgentFlow[] {
  const q = query.trim().toLowerCase();
  if (!q) return flows;
  return flows.filter((flow) =>
    [
      flow.title,
      flow.summary,
      flow.caveats,
      flow.question ?? "",
      flow.takeaway ?? "",
      ...flow.actors,
      ...(flow.detail ?? []),
    ]
      .join(" ")
      .toLowerCase()
      .includes(q),
  );
}
